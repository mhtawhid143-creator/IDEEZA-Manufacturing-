import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const url = readFileSync(process.argv[2], 'utf8').trim();
const site = url.split('/auth/')[0];
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1200 } })).newPage();
page.on('pageerror', (e) => console.log('pageerror: ' + String(e).slice(0, 200)));
await page.goto(url, { waitUntil: 'networkidle', timeout: 90000 });
await page.goto(`${site}/settings`, { waitUntil: 'networkidle', timeout: 90000 });
await page.getByRole('button', { name: 'Get Paid', exact: true }).click();
await page.waitForTimeout(1500);
console.log('add buttons: ' + (await page.getByRole('button', { name: 'Add method' }).count()));
await page.getByRole('button', { name: 'Add method' }).first().click();
await page.waitForTimeout(1200);
console.log('dialogs open: ' + (await page.getByRole('dialog').count()));
const dlg = page.getByRole('dialog').first();
console.log('dialog name: ' + (await dlg.getAttribute('aria-label')) + ' / ' + (await dlg.innerText()).split('\n')[0]);
console.log('labels: ' + JSON.stringify(await dlg.locator('label').allInnerTexts()));
console.log('inputs: ' + (await dlg.locator('input').count()) + ' selects: ' + (await dlg.locator('select').count()));
await browser.close();
